import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('offline-test/index.html','utf8');
const manifest=JSON.parse(fs.readFileSync('offline-test/manifest.webmanifest','utf8'));
const sw=fs.readFileSync('offline-test/sw.js','utf8');
const js=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]);
assert.ok(js.length,'app JS missing');
for(const script of js)new vm.Script(script);
new vm.Script(sw);
assert.equal(manifest.display,'standalone');
assert.equal(manifest.lang,'ar');
assert.ok(manifest.start_url.startsWith('./'));
for(const id of ['receiptDetails','receiptDetailsContent','closeReceiptDetails','records','archive','export','import','reminders'])assert.ok(html.includes('id="'+id+'"'),'missing '+id);
assert.ok(html.includes("String(b.created||'').localeCompare(String(a.created||''))"),'invoice insertion sorting missing');
assert.ok(html.includes("archiveState(x).kind==='delete'"),'expiry cleanup missing');
assert.ok(html.includes("s.delete(x.id)"),'expiry delete missing');
assert.ok(html.includes("b.dataset.action==='open'"),'invoice details handler missing');
assert.ok(sw.includes('offline-test-v41'),'unexpected offline cache version');
const assets=[...sw.matchAll(/'\.\/([^']+)'/g)].map(x=>x[1]).filter(Boolean);
for(const asset of assets)assert.ok(fs.existsSync('offline-test/'+asset),'missing offline asset: '+asset);
console.log('PASS: syntax, PWA metadata, UI hooks, archive cleanup, insertion order, offline asset paths');
console.log('LIMITATION: static tests do not validate iPhone background notifications, licensing server, real device installation or commercial readiness');
